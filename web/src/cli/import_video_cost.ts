export function createPrismaVideoCostImportRepository(
  db: PrismaDbClient,
): VideoCostImportRepositoryPort {
  return {
    async findGameBySteamAppId(steamAppId: string) {
      const game = await db.indieGame.findUnique({
        where: { steamAppId },
        select: {
          id: true,
          steamAppId: true,
          retailPriceJpy: true,
          isOperatorAffiliated: true,
          isApproved: true,
        },
      });
      return game;
    },

    async findSettlementStateByYearMonth(yearMonth: string) {
      const row = await db.monthlySettlement.findUnique({
        where: { yearMonth },
        select: { isSettled: true },
      });
      return row;
    },

    async existsByYoutubeVideoId(youtubeVideoId: string): Promise<boolean> {
      const count = await db.videoCostLedger.count({
        where: { youtubeVideoId },
      });
      return count > 0;
    },

    async hasBilledPlayLaborForFootageHash(
      rawFootageSha256: string,
    ): Promise<boolean> {
      const count = await db.videoCostLedger.count({
        where: {
          rawFootageSha256,
          playMinutes: { gt: 0 },
        },
      });
      return count > 0;
    },

    async hasBilledPlayLaborForGameInMonth(params: {
      readonly gameId: number;
      readonly startUtc: Date;
      readonly endExclusiveUtc: Date;
    }): Promise<boolean> {
      const count = await db.videoCostLedger.count({
        where: {
          gameId: params.gameId,
          publishedAt: {
            gte: params.startUtc,
            lt: params.endExclusiveUtc,
          },
          playMinutes: { gt: 0 },
        },
      });
      return count > 0;
    },

    async hasRecordingGameCostForGame(gameId: number): Promise<boolean> {
      const count = await db.videoCostLedger.count({
        where: {
          gameId,
          recordingGameCostJpy: { gt: 0 },
        },
      });
      return count > 0;
    },

    async insertVideoCostLedger(
      row: NewVideoCostLedgerRow,
    ): Promise<{ readonly id: number }> {
      const created = await db.videoCostLedger.create({
        data: {
          youtubeVideoId: row.youtubeVideoId,
          title: row.title,
          gameId: row.gameId,
          isSyntheticContent: row.isSyntheticContent,
          llmModelName: row.llmModelName,
          inputTokens: row.inputTokens,
          outputTokens: row.outputTokens,
          inputRateUsdPer1M: row.inputRateUsdPer1M,
          outputRateUsdPer1M: row.outputRateUsdPer1M,
          usdJpyRate: row.usdJpyRate,
          llmCostJpy: row.llmCostJpy,
          ttsCostJpy: row.ttsCostJpy,
          computeCostJpy: row.computeCostJpy,
          totalGenerationCost: row.totalGenerationCost,
          recordingGameCostJpy: row.recordingGameCostJpy,
          recordingGameReceiptUrl: row.recordingGameReceiptUrl,
          footageSource: row.footageSource,
          rawFootageSha256: row.rawFootageSha256,
          rawFootageSec: row.rawFootageSec,
          playRegionCode: row.playRegionCode,
          playMinutes: row.playMinutes,
          playLaborRateJpyPerHour: row.playLaborRateJpyPerHour,
          playLaborCostJpy: row.playLaborCostJpy,
          reviewRegionCode: row.reviewRegionCode,
          reviewMinutes: row.reviewMinutes,
          reviewLaborRateJpyPerHour: row.reviewLaborRateJpyPerHour,
          reviewLaborCostJpy: row.reviewLaborCostJpy,
          aiDisclosureSet: row.aiDisclosureSet,
          contentIdStatus: row.contentIdStatus,
          publishedAt: row.publishedAt,
        },
        select: { id: true },
      });
      return created;
    },
  };
}

export async function executeTransactionalVideoCostImport(params: {
  readonly prisma: PrismaClient;
  readonly request: VideoCostImportRequest;
  readonly logger: Logger;
  readonly publicConstants?: PublicConstantsConfig | undefined;
  readonly localeRaw?: string | undefined;
}): Promise<CreatedVideoCostLedgerSummary> {
  return params.prisma.$transaction(async (tx) => {
    const repo = createPrismaVideoCostImportRepository(tx);
    return importVideoCostRecord(params.request, {
      repo,
      logger: params.logger,
      publicConstants: params.publicConstants,
      localeRaw: params.localeRaw,
    });
  });
}

export type ParsedImportCliAction =
  | { readonly kind: "help"; readonly usageText: string }
  | {
      readonly kind: "engine_file";
      readonly filePath: string;
      readonly postUpload: PostUploadMetadataInput;
      readonly overridePlayRegionCode?: string | undefined;
    }
  | {
      readonly kind: "human_stream";
      readonly request: VideoCostImportRequest;
    };

function parseContentIdStatus(raw: string | undefined): LedgerContentIdStatus {
  if (!raw || raw.trim().length === 0) {
    return "CLEAR";
  }
  const normalized = raw.trim().toUpperCase();
  if (
    normalized === "CLEAR" ||
    normalized === "CLAIMED_REVENUE_REDIRECTED" ||
    normalized === "RESTRICTED"
  ) {
    return normalized;
  }
  throw new DomainValidationError("error.validation.invalid_json_report", {
    reason: `Unsupported --content-id-status: ${raw}`,
  });
}

function parseFootageSource(
  raw: string | undefined,
): LedgerFootageSource | undefined {
  if (!raw || raw.trim().length === 0) {
    return undefined;
  }
  const normalized = raw.trim().toUpperCase();
  if (
    normalized === "HUMAN_PLAY" ||
    normalized === "SECONDARY_CLIP" ||
    normalized === "BOT_PLAY"
  ) {
    return normalized;
  }
  throw new DomainValidationError("error.validation.invalid_json_report", {
    reason: `Unsupported --footage-source: ${raw}`,
  });
}

function parseOptionalIntFlag(
  flagName: string,
  raw: string | undefined,
): number | undefined {
  if (raw === undefined) {
    return undefined;
  }
  const trimmed = raw.trim();
  if (!/^-?\d+$/.test(trimmed)) {
    throw new DomainValidationError("error.validation.invalid_integer", {
      field: flagName,
      value: raw,
    });
  }
  const num = Number(trimmed);
  if (!Number.isSafeInteger(num)) {
    throw new DomainValidationError("error.validation.invalid_integer", {
      field: flagName,
      value: raw,
    });
  }
  return num;
}

export function parseImportCliArgs(
  argv: readonly string[],
): ParsedImportCliAction {
  let values: {
    help?: boolean;
    file?: string;
    "human-stream"?: boolean;
    "youtube-video-id"?: string;
    "ai-disclosure-ack"?: boolean;
    "published-at"?: string;
    "play-region"?: string;
    "review-region"?: string;
    "content-id-status"?: string;
    "steam-app-id"?: string;
    title?: string;
    "footage-source"?: string;
    "raw-footage-sha256"?: string;
    "raw-footage-sec"?: string;
    "recording-game-cost-jpy"?: string;
    "recording-game-receipt-url"?: string;
  };

  try {
    const parsed = parseArgs({
      args: [...argv],
      strict: true,
      allowPositionals: false,
      options: {
        help: { type: "boolean", short: "h" },
        file: { type: "string" },
        "human-stream": { type: "boolean" },
        "youtube-video-id": { type: "string" },
        "ai-disclosure-ack": { type: "boolean" },
        "published-at": { type: "string" },
        "play-region": { type: "string" },
        "review-region": { type: "string" },
        "content-id-status": { type: "string" },
        "steam-app-id": { type: "string" },
        title: { type: "string" },
        "footage-source": { type: "string" },
        "raw-footage-sha256": { type: "string" },
        "raw-footage-sec": { type: "string" },
        "recording-game-cost-jpy": { type: "string" },
        "recording-game-receipt-url": { type: "string" },
      },
    });
    values = parsed.values;
  } catch (err: unknown) {
    throw new DomainValidationError(
      "error.validation.missing_cli_arg",
      { arg: err instanceof Error ? err.message : String(err) },
      { cause: err },
    );
  }

  if (values.help) {
    return { kind: "help", usageText: IMPORT_CLI_USAGE_TEXT };
  }

  const hasFile = Boolean(values.file && values.file.trim().length > 0);
  const isHumanStream = Boolean(values["human-stream"]);
  if (hasFile === isHumanStream) {
    throw new DomainValidationError("error.validation.missing_cli_arg", {
      arg: "--file <report.json> | --human-stream",
    });
  }

  const youtubeVideoId = values["youtube-video-id"]?.trim() ?? "";
  if (youtubeVideoId.length === 0) {
    throw new DomainValidationError("error.validation.missing_cli_arg", {
      arg: "--youtube-video-id",
    });
  }

  const publishedAtRaw = values["published-at"]?.trim() ?? "";
  if (publishedAtRaw.length === 0) {
    throw new DomainValidationError("error.validation.missing_cli_arg", {
      arg: "--published-at",
    });
  }
  const publishedAt = new Date(publishedAtRaw);
  if (Number.isNaN(publishedAt.getTime())) {
    throw new DomainValidationError("error.validation.invalid_date", {
      field: "--published-at",
    });
  }

  const postUpload: PostUploadMetadataInput = {
    youtubeVideoId,
    publishedAt,
    reviewRegionCode: values["review-region"]?.trim() || "JP",
    contentIdStatus: parseContentIdStatus(values["content-id-status"]),
    aiDisclosureAck: Boolean(values["ai-disclosure-ack"]),
  };

  if (hasFile && values.file) {
    return {
      kind: "engine_file",
      filePath: values.file.trim(),
      postUpload,
      overridePlayRegionCode: values["play-region"]?.trim() || undefined,
    };
  }

  const steamAppId = values["steam-app-id"]?.trim() ?? "";
  if (steamAppId.length === 0) {
    throw new DomainValidationError("error.validation.missing_cli_arg", {
      arg: "--steam-app-id",
    });
  }
  const videoTitle = values.title?.trim() ?? "";
  if (videoTitle.length === 0) {
    throw new DomainValidationError("error.validation.missing_cli_arg", {
      arg: "--title",
    });
  }

  return {
    kind: "human_stream",
    request: {
      mode: "human_stream",
      steamAppId,
      videoTitle,
      playRegionCode: values["play-region"]?.trim() || "JP",
      postUpload,
      footageSource: parseFootageSource(values["footage-source"]),
      rawFootageSha256: values["raw-footage-sha256"]?.trim() || null,
      rawFootageSec: parseOptionalIntFlag(
        "--raw-footage-sec",
        values["raw-footage-sec"],
      ),
      recordingGameCostJpy: parseOptionalIntFlag(
        "--recording-game-cost-jpy",
        values["recording-game-cost-jpy"],
      ),
      recordingGameReceiptUrl:
        values["recording-game-receipt-url"]?.trim() || null,
    },
  };
}

export function loadRawJsonReportFile(filePath: string): unknown {
  let rawText: string;
  try {
    rawText = readFileSync(resolve(filePath), "utf8");
  } catch (err: unknown) {
    throw new DomainValidationError(
      "error.validation.invalid_json_report",
      { reason: err instanceof Error ? err.message : String(err) },
      { cause: err },
    );
  }

  try {
    return JSON.parse(rawText) as unknown;
  } catch (err: unknown) {
    throw new DomainValidationError(
      "error.validation.invalid_json_report",
      { reason: err instanceof Error ? err.message : String(err) },
      { cause: err },
    );
  }
}

async function main(): Promise<void> {
  const locale = resolveLocale(process.env["APP_LOCALE"]);
  const logger = createStructuredLogger({ service: "zerocut-import-cli" });
  const parsed = parseImportCliArgs(process.argv.slice(2));

  if (parsed.kind === "help") {
    process.stdout.write(`${parsed.usageText}\n`);
    return;
  }

  const request: VideoCostImportRequest =
    parsed.kind === "engine_file"
      ? {
          mode: "engine_file",
          rawReport: loadRawJsonReportFile(parsed.filePath),
          postUpload: parsed.postUpload,
          overridePlayRegionCode: parsed.overridePlayRegionCode,
        }
      : parsed.request;

  const prisma = createPrismaClient();
  try {
    await executeTransactionalVideoCostImport({
      prisma,
      request,
      logger,
      localeRaw: locale,
    });
  } finally {
    await prisma.$disconnect();
  }
}

